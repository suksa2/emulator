"""Исключения, используемые эмулятором."""


class ShellError(Exception):
    """Ошибка выполнения команды (неизвестная команда, неверные аргументы)."""


class ExitRequest(Exception):
    """Запрос на завершение работы эмулятора с заданным кодом возврата."""

    def __init__(self, code=0):
        """Сохраняет код возврата."""
        super().__init__(code)
        self.code = code
